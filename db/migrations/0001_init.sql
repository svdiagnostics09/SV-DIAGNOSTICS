-- SV Diagnostics — initial schema (Phase 1)
-- All money is stored in integer paise. All timestamps are timestamptz in UTC;
-- appointment dates are stored as a local (Asia/Kolkata) calendar date.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
-- ---------------------------------------------------------------- identity
CREATE TABLE IF NOT EXISTS users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL,
  name text NOT NULL DEFAULT '',
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'owner')),
  is_active boolean NOT NULL DEFAULT true,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (lower(email));
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions (user_id);
CREATE TABLE IF NOT EXISTS customer_profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  phone text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS patients (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id uuid REFERENCES customer_profiles(id) ON DELETE
  SET NULL,
    name text NOT NULL,
    relationship text NOT NULL DEFAULT 'self',
    date_of_birth date,
    gender text CHECK (gender IN ('male', 'female', 'other')),
    notes text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
-- ---------------------------------------------------------------- catalogue
CREATE TABLE IF NOT EXISTS diagnostic_categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS investigations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS investigations_name_key ON investigations (lower(name));
CREATE TABLE IF NOT EXISTS diagnostic_tests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer REFERENCES diagnostic_categories(id) ON DELETE RESTRICT,
  name text NOT NULL,
  slug text NOT NULL,
  short_description text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  sample_type text NOT NULL DEFAULT '',
  sample_types text [] NOT NULL DEFAULT '{}',
  report_type text NOT NULL DEFAULT '',
  turnaround_hours integer CHECK (
    turnaround_hours IS NULL
    OR turnaround_hours > 0
  ),
  preparation text NOT NULL DEFAULT '',
  fasting_required boolean NOT NULL DEFAULT false,
  fasting_hours integer CHECK (
    fasting_hours IS NULL
    OR fasting_hours BETWEEN 0 AND 48
  ),
  price_paise integer NOT NULL CHECK (price_paise > 0),
  discount_type text NOT NULL DEFAULT 'none' CHECK (discount_type IN ('none', 'percent', 'amount')),
  discount_value integer NOT NULL DEFAULT 0 CHECK (discount_value >= 0),
  home_collection boolean NOT NULL DEFAULT true,
  is_popular boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  image_url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT diagnostic_tests_discount_check CHECK (
    (
      discount_type = 'none'
      AND discount_value = 0
    )
    OR (
      discount_type = 'percent'
      AND discount_value BETWEEN 1 AND 100
    )
    OR (
      discount_type = 'amount'
      AND discount_value > 0
      AND discount_value < price_paise
    )
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS diagnostic_tests_slug_key ON diagnostic_tests (slug);
CREATE INDEX IF NOT EXISTS diagnostic_tests_status_idx ON diagnostic_tests (status, category_id);
CREATE INDEX IF NOT EXISTS diagnostic_tests_name_idx ON diagnostic_tests (lower(name));
CREATE TABLE IF NOT EXISTS test_investigations (
  test_id integer NOT NULL REFERENCES diagnostic_tests(id) ON DELETE CASCADE,
  investigation_id integer NOT NULL REFERENCES investigations(id) ON DELETE RESTRICT,
  PRIMARY KEY (test_id, investigation_id)
);
CREATE TABLE IF NOT EXISTS health_packages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  preparation text NOT NULL DEFAULT '',
  sample_type text NOT NULL DEFAULT '',
  turnaround_hours integer CHECK (
    turnaround_hours IS NULL
    OR turnaround_hours > 0
  ),
  price_paise integer NOT NULL CHECK (price_paise > 0),
  original_price_paise integer CHECK (
    original_price_paise IS NULL
    OR original_price_paise > 0
  ),
  home_collection boolean NOT NULL DEFAULT true,
  is_popular boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  image_url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT health_packages_original_check CHECK (
    original_price_paise IS NULL
    OR original_price_paise >= price_paise
  )
);
CREATE TABLE IF NOT EXISTS package_tests (
  package_id integer NOT NULL REFERENCES health_packages(id) ON DELETE CASCADE,
  test_id integer NOT NULL REFERENCES diagnostic_tests(id) ON DELETE RESTRICT,
  PRIMARY KEY (package_id, test_id)
);
-- ---------------------------------------------------------------- network
CREATE TABLE IF NOT EXISTS locations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  address_line1 text NOT NULL,
  address_line2 text NOT NULL DEFAULT '',
  area text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT 'Hyderabad',
  state text NOT NULL DEFAULT 'Telangana',
  pincode text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  maps_url text NOT NULL DEFAULT '',
  opening_hours text NOT NULL DEFAULT '',
  services text [] NOT NULL DEFAULT '{}',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS service_areas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  city text NOT NULL DEFAULT 'Hyderabad',
  pincodes text [] NOT NULL DEFAULT '{}',
  home_collection boolean NOT NULL DEFAULT true,
  collection_fee_paise integer NOT NULL DEFAULT 0 CHECK (collection_fee_paise >= 0),
  operating_hours text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS collection_slots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer REFERENCES locations(id) ON DELETE CASCADE,
  method text NOT NULL DEFAULT 'both' CHECK (method IN ('home', 'lab', 'both')),
  label text NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  duration_minutes integer NOT NULL DEFAULT 60 CHECK (duration_minutes > 0),
  daily_capacity integer NOT NULL DEFAULT 10 CHECK (daily_capacity >= 0),
  weekdays smallint [] NOT NULL DEFAULT '{0,1,2,3,4,5,6}',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS collection_slots_location_idx ON collection_slots (location_id, method);
CREATE TABLE IF NOT EXISTS slot_blackouts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer REFERENCES locations(id) ON DELETE CASCADE,
  slot_id integer REFERENCES collection_slots(id) ON DELETE CASCADE,
  blackout_date date NOT NULL,
  reason text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS slot_blackouts_day_key ON slot_blackouts (
  COALESCE(location_id, 0),
  COALESCE(slot_id, 0),
  blackout_date
);
CREATE TABLE IF NOT EXISTS slot_reservations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slot_id integer NOT NULL REFERENCES collection_slots(id) ON DELETE RESTRICT,
  location_id integer REFERENCES locations(id) ON DELETE
  SET NULL,
    method text NOT NULL CHECK (method IN ('home', 'lab')),
    slot_date date NOT NULL,
    capacity integer NOT NULL,
    booked integer NOT NULL DEFAULT 0 CHECK (
      booked >= 0
      AND booked <= capacity
    ),
    holds integer NOT NULL DEFAULT 0 CHECK (
      holds >= 0
      AND holds <= capacity
    ),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT slot_reservations_booked_capacity CHECK (booked + holds <= capacity)
);
CREATE UNIQUE INDEX IF NOT EXISTS slot_reservations_key ON slot_reservations (slot_id, COALESCE(location_id, 0), slot_date);
CREATE TABLE IF NOT EXISTS slot_holds (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reservation_id uuid NOT NULL REFERENCES slot_reservations(id) ON DELETE CASCADE,
  booking_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  released_at timestamptz
);
CREATE INDEX IF NOT EXISTS slot_holds_expiry_idx ON slot_holds (expires_at)
WHERE released_at IS NULL;
-- ---------------------------------------------------------------- bookings
CREATE TABLE IF NOT EXISTS bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE,
  access_token text NOT NULL,
  patient_id uuid REFERENCES patients(id) ON DELETE
  SET NULL,
    patient_name text NOT NULL,
    patient_age integer CHECK (
      patient_age IS NULL
      OR (
        patient_age >= 0
        AND patient_age <= 120
      )
    ),
    patient_gender text CHECK (patient_gender IN ('male', 'female', 'other')),
    phone text NOT NULL,
    email text,
    method text NOT NULL CHECK (method IN ('home', 'lab')),
    location_id integer REFERENCES locations(id) ON DELETE RESTRICT,
    service_area_id integer REFERENCES service_areas(id) ON DELETE RESTRICT,
    address_line text NOT NULL DEFAULT '',
    address_area text NOT NULL DEFAULT '',
    pincode text NOT NULL DEFAULT '',
    appointment_date date NOT NULL,
    slot_id integer NOT NULL REFERENCES collection_slots(id) ON DELETE RESTRICT,
    slot_label text NOT NULL,
    reservation_id uuid REFERENCES slot_reservations(id) ON DELETE
  SET NULL,
    subtotal_paise integer NOT NULL CHECK (subtotal_paise >= 0),
    discount_paise integer NOT NULL DEFAULT 0 CHECK (discount_paise >= 0),
    collection_fee_paise integer NOT NULL DEFAULT 0 CHECK (collection_fee_paise >= 0),
    total_paise integer NOT NULL CHECK (total_paise >= 0),
    payment_method text NOT NULL CHECK (
      payment_method IN ('online', 'pay_lab', 'pay_home')
    ),
    payment_status text NOT NULL DEFAULT 'pending' CHECK (
      payment_status IN (
        'pending',
        'paid',
        'failed',
        'refunded',
        'cancelled'
      )
    ),
    status text NOT NULL DEFAULT 'pending_confirmation' CHECK (
      status IN (
        'pending_confirmation',
        'confirmed',
        'collection_scheduled',
        'sample_collected',
        'processing',
        'report_ready',
        'completed',
        'cancelled'
      )
    ),
    consent_accepted boolean NOT NULL DEFAULT false,
    consent_ref uuid,
    idempotency_key text,
    internal_notes text NOT NULL DEFAULT '',
    cancellation_reason text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT bookings_home_fields CHECK (
      method = 'lab'
      OR (
        location_id IS NULL
        AND pincode <> ''
        AND address_line <> ''
      )
    ),
    CONSTRAINT bookings_lab_location CHECK (
      method = 'home'
      OR location_id IS NOT NULL
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS bookings_idempotency_key ON bookings (idempotency_key)
WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS bookings_status_idx ON bookings (status, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_phone_idx ON bookings (phone);
CREATE INDEX IF NOT EXISTS bookings_day_idx ON bookings (appointment_date);
CREATE TABLE IF NOT EXISTS booking_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('test', 'package')),
  test_id integer REFERENCES diagnostic_tests(id) ON DELETE RESTRICT,
  package_id integer REFERENCES health_packages(id) ON DELETE RESTRICT,
  name_snapshot text NOT NULL,
  unit_price_paise integer NOT NULL CHECK (unit_price_paise >= 0),
  list_price_paise integer NOT NULL CHECK (list_price_paise >= 0),
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  CONSTRAINT booking_items_target CHECK (
    (
      kind = 'test'
      AND test_id IS NOT NULL
      AND package_id IS NULL
    )
    OR (
      kind = 'package'
      AND package_id IS NOT NULL
      AND test_id IS NULL
    )
  )
);
CREATE INDEX IF NOT EXISTS booking_items_booking_idx ON booking_items (booking_id);
CREATE TABLE IF NOT EXISTS booking_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id uuid NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  kind text NOT NULL,
  message text NOT NULL,
  actor text NOT NULL DEFAULT 'system',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS booking_events_booking_idx ON booking_events (booking_id, created_at);
CREATE TABLE IF NOT EXISTS payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  provider text NOT NULL DEFAULT 'razorpay',
  provider_order_id text NOT NULL,
  provider_payment_id text,
  amount_paise integer NOT NULL CHECK (amount_paise > 0),
  currency text NOT NULL DEFAULT 'INR',
  status text NOT NULL DEFAULT 'created' CHECK (
    status IN (
      'created',
      'paid',
      'failed',
      'refunded',
      'cancelled'
    )
  ),
  method text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_order_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS payments_provider_payment_key ON payments (provider, provider_payment_id)
WHERE provider_payment_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS payments_booking_idx ON payments (booking_id);
CREATE TABLE IF NOT EXISTS payment_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id uuid REFERENCES payments(id) ON DELETE CASCADE,
  booking_id uuid REFERENCES bookings(id) ON DELETE CASCADE,
  provider text NOT NULL DEFAULT 'razorpay',
  event_id text NOT NULL,
  event_type text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  processed_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS payment_events_event_key ON payment_events (provider, event_id);
CREATE TABLE IF NOT EXISTS consent_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid REFERENCES bookings(id) ON DELETE CASCADE,
  consent_type text NOT NULL,
  version text NOT NULL,
  accepted boolean NOT NULL,
  accepted_at timestamptz NOT NULL DEFAULT now(),
  ip_hash text NOT NULL DEFAULT '',
  user_agent text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid REFERENCES bookings(id) ON DELETE
  SET NULL,
    channel text NOT NULL CHECK (
      channel IN ('email', 'sms', 'whatsapp', 'in_app')
    ),
    recipient text NOT NULL DEFAULT '',
    template text NOT NULL,
    status text NOT NULL DEFAULT 'queued' CHECK (
      status IN ('queued', 'sent', 'failed', 'skipped')
    ),
    detail text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    sent_at timestamptz
);
CREATE INDEX IF NOT EXISTS notifications_created_idx ON notifications (created_at DESC);
CREATE TABLE IF NOT EXISTS audit_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES users(id) ON DELETE
  SET NULL,
    actor_email text NOT NULL DEFAULT '',
    action text NOT NULL,
    entity text NOT NULL,
    entity_id text NOT NULL DEFAULT '',
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    ip_hash text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_logs_created_idx ON audit_logs (created_at DESC);
-- ---------------------------------------------------------------- content
CREATE TABLE IF NOT EXISTS enquiries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE,
  name text NOT NULL,
  phone text NOT NULL,
  email text NOT NULL DEFAULT '',
  subject text NOT NULL DEFAULT '',
  message text NOT NULL,
  status text NOT NULL DEFAULT 'new' CHECK (
    status IN ('new', 'in_progress', 'resolved', 'archived')
  ),
  internal_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS enquiries_status_idx ON enquiries (status, created_at DESC);
CREATE TABLE IF NOT EXISTS banners (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  subtitle text NOT NULL DEFAULT '',
  cta_label text NOT NULL DEFAULT '',
  cta_href text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  placement text NOT NULL DEFAULT 'home' CHECK (placement IN ('home', 'catalogue', 'packages')),
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS faqs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question text NOT NULL,
  answer text NOT NULL,
  category text NOT NULL DEFAULT 'General',
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS blog_posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  slug text NOT NULL UNIQUE,
  excerpt text NOT NULL DEFAULT '',
  body text NOT NULL DEFAULT '',
  cover_image_url text NOT NULL DEFAULT '',
  author text NOT NULL DEFAULT 'SV Diagnostics',
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS business_settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS login_attempts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS login_attempts_key_idx ON login_attempts (key, created_at DESC);